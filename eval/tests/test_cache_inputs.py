from dataclasses import replace
from pathlib import Path
import sys

from ultron.eval.benchmarks import BenchmarkId, BenchmarkJob, IterationStage
from ultron.eval.cache_inputs import actual_cache_inputs
from ultron.eval.execution import cache_key
from ultron.train.schema_v1 import Role


def local_job(tmp_path):
    harness = tmp_path / "harness"
    harness.mkdir()
    executable = harness / "pier"
    executable.write_text(f"#!{sys.executable}\nprint('fixture')\n")
    executable.chmod(0o755)
    dataset = tmp_path / "tasks"
    dataset.mkdir()
    (dataset / "task.txt").write_text("frozen task input")
    output = tmp_path / "output"
    job = BenchmarkJob(BenchmarkId.DEEP_SWE, Role.ATTACKER,
                       IterationStage(0, Role.ATTACKER, "grpo", 1, tmp_path / "adapter"),
                       (str(executable), "run", "-p", str(dataset), "--model", "attacker-frozen", "-o", str(output)),
                       (), None, output, "", "score",
                       {"dataset_revision": "a" * 40, "harness_revision": "b" * 40,
                        "seed": 0, "opponent_id": "none", "inference_settings": {"temperature": 1},
                        "local_inputs": {"harness_root": str(harness), "dataset_root": str(dataset)}})
    entry = {"adapter_sha256": "c" * 64, "base_model_revision": "d" * 40}
    return job, entry


def test_metadata_claims_cannot_enable_cache_for_unresolved_inputs(tmp_path):
    job, entry = local_job(tmp_path)
    context = {key: value for key, value in job.cache_context.items() if key != "local_inputs"}
    assert cache_key(replace(job, cache_context=context), entry) is None
    remote = replace(job, benchmark=BenchmarkId.TERMINAL_BENCH,
                     argv=(job.argv[0], "run", "-d", "terminal-bench/terminal-bench@latest", "--model", "attacker-frozen"))
    assert actual_cache_inputs(remote) is None
    assert cache_key(remote, entry) is None
    # A declared local root also cannot certify an unresolved remote commit/ref.
    pinned_remote = replace(remote, argv=(job.argv[0], "run", "-d", "terminal-bench/terminal-bench@" + "a" * 40))
    assert cache_key(pinned_remote, entry) is None


def test_actual_dataset_and_harness_content_change_cache_identity(tmp_path):
    job, entry = local_job(tmp_path)
    before = actual_cache_inputs(job)
    key = cache_key(job, entry)
    assert before is not None and key is not None
    dataset = Path(job.cache_context["local_inputs"]["dataset_root"])
    (dataset / "task.txt").write_text("changed without updating the declared revision")
    assert actual_cache_inputs(job)["dataset_sha256"] != before["dataset_sha256"]
    assert cache_key(job, entry) != key
    key = cache_key(job, entry)
    Path(job.argv[0]).write_text(f"#!{sys.executable}\nprint('changed harness implementation')\n")
    assert cache_key(job, entry) != key


def test_root_must_match_the_dataset_selected_by_the_command(tmp_path):
    job, entry = local_job(tmp_path)
    other = tmp_path / "other-tasks"
    other.mkdir()
    (other / "task.txt").write_text("different selected tasks")
    args = list(job.argv)
    args[args.index("-p") + 1] = str(other)
    assert cache_key(replace(job, argv=tuple(args)), entry) is None
    unrelated = tmp_path / "unrelated-harness"
    unrelated.mkdir()
    (unrelated / "version.txt").write_text("same claimed revision")
    context = {**job.cache_context, "local_inputs": {**job.cache_context["local_inputs"], "harness_root": str(unrelated)}}
    assert cache_key(replace(job, cache_context=context), entry) is None


def test_cache_identity_ignores_generated_bytecode_and_output_location(tmp_path):
    job, entry = local_job(tmp_path)
    key = cache_key(job, entry)
    assert key is not None
    root = Path(job.cache_context["local_inputs"]["harness_root"])
    bytecode = root / "__pycache__"
    bytecode.mkdir()
    (bytecode / "cache.cpython.pyc").write_bytes(b"generated bytecode")
    assert cache_key(job, entry) == key
    different_output = tmp_path / "different-output"
    args = tuple(str(different_output) if item == str(job.workdir) else item for item in job.argv)
    assert cache_key(replace(job, workdir=different_output, argv=args), entry) == key
    assert cache_key(replace(job, workdir=root / "results"), entry) is None


def test_fingerprinting_never_runs_the_harness_entrypoint(tmp_path):
    job, _ = local_job(tmp_path)
    marker = tmp_path / "entrypoint-was-executed"
    Path(job.argv[0]).write_text(f"#!{sys.executable}\nfrom pathlib import Path\nPath({str(marker)!r}).write_text('executed')\n")
    assert actual_cache_inputs(job) is not None
    assert not marker.exists()


def test_console_entrypoint_links_to_its_actual_installed_source_without_importing_it(tmp_path):
    job, entry = local_job(tmp_path)
    site = tmp_path / "site-packages"
    package = site / "fixture_harness"
    package.mkdir(parents=True)
    (package / "__init__.py").write_text("raise RuntimeError('do not import the harness during fingerprinting')\n")
    implementation = package / "cli.py"
    implementation.write_text("def main():\n    return 0\n")
    distribution = site / "fixture_harness-1.0.dist-info"
    distribution.mkdir()
    (distribution / "METADATA").write_text("Metadata-Version: 2.1\nName: fixture-harness\nVersion: 1.0\n")
    (distribution / "entry_points.txt").write_text("[console_scripts]\nultron-fixture-harness = fixture_harness.cli:main\n")
    binary = tmp_path / "bin" / "ultron-fixture-harness"
    binary.parent.mkdir()
    binary.write_text(f"#!{sys.executable}\nimport sys\nfrom fixture_harness.cli import main\nsys.exit(main())\n")
    binary.chmod(0o755)
    context = {**job.cache_context, "local_inputs": {**job.cache_context["local_inputs"], "harness_root": str(package)}}
    job = replace(job, argv=(str(binary), *job.argv[1:]), env=(("PYTHONPATH", str(site)),), cache_context=context)
    observed = actual_cache_inputs(job)
    assert observed is not None
    assert observed["python"]["entries"][0]["distribution"] == "fixture-harness"
    key = cache_key(job, entry)
    implementation.write_text("def main():\n    return 1\n")
    assert cache_key(job, entry) != key
    (distribution / "entry_points.txt").write_text("[console_scripts]\nultron-fixture-harness = unrelated.cli:main\n")
    assert actual_cache_inputs(job) is None
